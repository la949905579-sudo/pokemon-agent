def my_mon(slot=0):
    """读队伍第 slot 只的 等级/HP/maxHP/招式/PP/属性(特攻)。"""
    base = PARTY_ADDR + slot * 100
    d = rd(base, 100)
    if len(d) < 100:
        return None
    lv = d[0x54]
    hp, mhp = struct.unpack_from("<HH", d, 0x56)
    pid = struct.unpack_from("<I", d, 0)[0]
    otid = struct.unpack_from("<I", d, 4)[0]
    key = pid ^ otid
    raw = d[0x20:0x20 + 48]
    words = [struct.unpack_from("<I", raw, i)[0] ^ key for i in range(0, 48, 4)]
    sb = b"".join(struct.pack("<I", w) for w in words)
    TABLE = ["GAEM","GAME","GEAM","GEMA","GMAE","GMEA","AGEM","AGME","AEGM","AEMG","AMGE","AMEG",
             "EGAM","EGMA","EAGM","EAMG","EMGA","EMAG","MGAE","MGEA","MAGE","MAEG","MEGA","MEAG"]
    seq = TABLE[pid % 24]
    i = seq.index("A")
    att = sb[i*12:(i+1)*12]
    moves = [struct.unpack_from("<H", att, j*2)[0] for j in range(4)]
    pp = list(att[8:12])
    # growth substruct 的第 1 个 u16 是 species
    gi = seq.index("G")
    growth = sb[gi*12:(gi+1)*12]
    species = struct.unpack_from("<H", growth, 0)[0]
    return {"slot": slot, "lv": lv, "hp": hp, "mhp": mhp, "moves": moves, "pp": pp,
            "species": species, "types": SPECIES_TYPES.get(species, ())}


def move_effect(mid, enemy_types):
    info = MOVES.get(mid)
    if not info or info[2] <= 0 or not enemy_types:
        return 1.0
    eff = 1.0
    for et in enemy_types:
        eff *= TYPE_CHART.get((info[1], et), 1.0)
    return eff


def choose_switch(enemy_types, enemy_lv, exclude_slot=None):
    """换人策略：优先克制敌方且等级不太低；否则等级最高且不被克制。"""
    cands = []
    for i in range(6):
        m = my_mon(i)
        if not m or m["hp"] <= 0 or i == exclude_slot:
            continue
        cands.append((i, m))
    if not cands:
        return None
    # 1) 有克制招式的
    killers = []
    for i, m in cands:
        eff = max((move_effect(mid, enemy_types) for mid in m["moves"]), default=1.0)
        if eff > 1.0:
            killers.append((i, m, eff))
    if killers:
        killers.sort(key=lambda x: -x[1]["lv"])
        i, m, eff = killers[0]
        if m["lv"] >= enemy_lv - 5:
            return i
    # 2) 等级最高且不被敌方属性克制
    safe = []
    for i, m in cands:
        dmg = 1.0
        for et in enemy_types:
            for mt in m["types"]:
                dmg *= TYPE_CHART.get((et, mt), 1.0)
        if dmg <= 1.0:
            safe.append((i, m))
    pool = safe or cands
    pool.sort(key=lambda x: -x[1]["lv"])
    return pool[0][0]


def choose_move(mon, enemy_types=None):
    """返回 (招式序号 0-3, 说明)。优先克制，其次威力，PP 为 0 跳过。"""
    best = None
    for i, (mid, pp) in enumerate(zip(mon["moves"], mon["pp"])):
        info = MOVES.get(mid)
        if not info or pp <= 0:
            continue
        name, typ, power = info
        if power <= 0:
            continue
        eff = 1.0
        if enemy_types:
            for et in enemy_types:
                eff *= TYPE_CHART.get((typ, et), 1.0)
        score = power * eff
        if best is None or score > best[0]:
            best = (score, i, name, typ, power, eff)
    if best is None:
        return 0, "没有可用攻击招式，默认第一招"
    return best[1], f"{best[2]}（{best[3]} 威力{best[4]} 克制x{best[5]:g}）"


