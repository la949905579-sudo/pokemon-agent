def enemy_info():
    d = rd(ENEMY_BASE, 8)
    if len(d) < 8:
        return None
    lv = d[0]
    hp, mhp = struct.unpack_from("<HH", d, 2)
    sp = rd(ENEMY_SPECIES, 2)
    species = struct.unpack("<H", sp)[0] if sp and len(sp) == 2 else None
    types = SPECIES_TYPES.get(species, ())
    return {"lv": lv, "hp": hp, "mhp": mhp, "species": species, "types": types}


